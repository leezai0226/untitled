import { pricing, longTermDiscounts } from "@/config/production";

/**
 * FAQ 데이터 — FaqSection(화면)과 production/layout(FAQPage 구조화 데이터)에서 공유.
 * "use client" 가 없는 순수 모듈이어야 서버 컴포넌트에서도 호출할 수 있습니다.
 * 계약 기간은 config 의 minContractMonths 를 읽는다 (0이면 "상담 시 안내").
 */
export type FaqItem = { q: string; a: string };

export function buildFaqs(): FaqItem[] {
  const discounts = longTermDiscounts.filter((d) => d.rate.trim());
  const discountNote = discounts.length
    ? ` 기본은 월 단위 계약이고, ${discounts
        .map((d) => `${d.months}개월 이상 약정 시 월 요금 ${d.rate}`)
        .join(", ")} 할인이 적용됩니다.`
    : "";

  const contractAnswer =
    pricing.minContractMonths > 0
      ? `기본 계약 기간은 ${pricing.minContractMonths}개월입니다. 유튜브는 한두 달 만에 결과가 나오는 매체가 아니라서, 최소한의 호흡을 두고 함께 가는 것을 권해 드립니다.${discountNote} 자세한 조건은 상담에서 안내드립니다.`
      : `계약 기간은 상담에서 채널 상황과 목표에 맞춰 안내드립니다. 유튜브는 한두 달 만에 결과가 나오는 매체가 아니라서, 최소한의 호흡을 두고 함께 가는 것을 권해 드립니다.${discountNote}`;

  return [
    {
      q: "얼굴이 꼭 나와야 하나요?",
      a: "꼭 그렇지는 않습니다. 다만 병원·법률 분야는 “누가 말하는가”가 신뢰에 큰 영향을 주기 때문에, 가능하다면 출연을 권해 드립니다. 얼굴 공개가 어려우시면 손·자료 화면 중심 구성 등 대안을 진단 단계에서 함께 찾습니다.",
    },
    {
      q: "촬영은 어디서 하나요?",
      a: "병원·사무실로 저희가 방문하는 것이 기본입니다. 진료실이나 상담실 배경이 오히려 신뢰를 줍니다. 원하시면 스튜디오 촬영도 가능합니다.",
    },
    {
      q: "대본은 누가 쓰나요?",
      a: "기획과 구성은 저희가 만듭니다. 다만 “읽는 대본”이 아니라 키워드 중심으로 정리해 드려서, 평소 환자분·의뢰인에게 설명하시듯 말씀하시면 됩니다. 외우실 필요가 없습니다.",
    },
    {
      q: "의료광고·변호사 광고 규정은 어떻게 챙기나요?",
      a: "기획 단계에서 먼저 점검합니다. “최고”, “유일”, “100% 해결” 같은 과장·단정 표현은 대본이 되기 전에 걷어내고, 환자·의뢰인 사례는 누구인지 알 수 없게 각색하는 것을 원칙으로 합니다. 치료 효과나 결과를 단정하는 대신 “이런 경우에 이런 선택지가 있습니다”로 말하는 방식을 함께 설계합니다. 최종 심의와 규정 판단은 소속 협회 기준을 따릅니다.",
    },
    {
      q: "계약 기간은 어떻게 되나요?",
      a: contractAnswer,
    },
    {
      q: "이미 채널이 있는데, 중간부터 맡길 수 있나요?",
      a: "네, 가능합니다. 기존 채널의 영상과 데이터를 보고 무엇을 유지하고 무엇을 바꿀지 진단부터 시작합니다. 처음부터 다시 만드는 것보다 효율적인 경우가 많습니다.",
    },
    {
      q: "진단만 받아봐도 되나요?",
      a: "물론입니다. 기획 진단은 그 자체로 완결된 상품입니다. 진단 리포트를 받아보시고 직접 운영하셔도 되고, 필요하실 때 다시 찾아주셔도 됩니다.",
    },
  ];
}
